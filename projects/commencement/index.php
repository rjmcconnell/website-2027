					<p>Pratt Institute&rsquo;s annual Commencement ceremony is a tradition that takes place every year at Radio City Music Hall. Starting in 2023, the decision was made to develop a design system that could be used year over year, rather than building a self-contained design direction for each individual year as had been done previously.</p>
					<p>For Commencement, I developed a design system based on the notion of continuity: the idea that one retains the ties to friends, mentors and the Pratt community even after passing over the threshold of graduation. Visually, this is represented typographically by a long, repeated band of text that adapts to many situations and different types of messaging. Rather than limiting color to the institutional yellow, as had been done in previous years, the palette is expanded into &ldquo;Pratt yellow plus everything&rdquo; to celebrate the multifaceted and diverse nature of each year&rsquo;s graduating class.</p>
